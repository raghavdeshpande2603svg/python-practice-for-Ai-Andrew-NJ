#Logical operators perform the Logical AND logical OR and Logical NOT operations on the give components

a = True
b = False
print (a and b)
print (a or b)
print (not a)

#is and is not operators are used to check the identity of the given components
#is if the operands is equal to the given components 
#is not if the operands is not equal to the given components
#not in used to check the negation of the given components
